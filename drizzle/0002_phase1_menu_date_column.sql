-- فاز ۱-۴ — ستون «روز منو» از timestamp به نوع date (روز تقویمی تهران)
-- ══════════════════════════════════════════════════════════════════════
-- چرا: یک «روز منو» یک مفهوم تقویمی است، نه یک لحظهٔ زمانی. ذخیرهٔ آن به‌صورت
-- timestamp باعث می‌شد مقدارِ ذخیره‌شده به TZ سرور و رفتار درایور وابسته شود و
-- مقایسه‌های «امروز / این هفته» در مرز نیمه‌شب لغزش کنند.
--
-- قاعدهٔ تبدیل داده‌های موجود: مقادیر قبلی به‌عنوان «زمان دیواری تهران» تفسیر
-- می‌شوند و بخش تقویمی همان روز نگه داشته می‌شود. چون ایران از سال ۱۴۰۱ ساعت
-- تابستانی ندارد و افست +03:30 ثابت است، این تبدیل برای همهٔ ردیف‌ها یکتا و
-- قطعی است و روز تقویمی هیچ منویی جابه‌جا نمی‌شود.
--
-- TIME ZONE نشست روی Asia/Tehran تنظیم می‌شود تا نتیجهٔ تبدیل مستقل از TZ
-- سروری باشد که migration را اجرا می‌کند (migrator درون تراکنش اجرا می‌شود).
--
-- ایندکس‌های menus_date_slot_idx و menus_date_slot_live_idx توسط خودِ
-- PostgreSQL روی نوع جدید بازسازی می‌شوند.

SET TIME ZONE 'Asia/Tehran';--> statement-breakpoint
ALTER TABLE "menus" ALTER COLUMN "date" SET DATA TYPE date
  USING (("date" AT TIME ZONE 'Asia/Tehran')::date);--> statement-breakpoint
ALTER TABLE "menus" ADD CONSTRAINT "menus_date_not_epoch_check" CHECK ("menus"."date" > '1970-01-02');
